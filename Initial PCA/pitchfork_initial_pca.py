import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

"This cell sets up our dataframe and gives us a full list of columns"

# Our pitchfork data
pitchfork = "/content/drive/MyDrive/Colab Notebooks/Datasets/pitchfork.csv"
review_df = df=pd.read_csv(pitchfork)

# Default look for every plot in the notebook.
sns.set_theme(style="whitegrid", context="notebook")
pd.set_option("display.max_columns", 20)
pd.set_option("display.width", 120)

review_df.columns

from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import StandardScaler, OneHotEncoder
from sklearn.impute import SimpleImputer
from sklearn.pipeline import Pipeline
from sklearn.decomposition import PCA

"This cell excludes columns which are not of interest and defines score as our main variable to predict"

# 1. Define the target and features
target = "score"

features = [
    "releaseyear",
    "danceability",
    "energy",
    "key",
    "loudness",
    "speechiness",
    "acousticness",
    "instrumentalness",
    "liveness",
    "valence",
    "tempo"
]

# 2. Separate the score from the predictor features
X = review_df[features]
y = review_df[target]

"This cell fills empty values (should there be any) with median and standardizes value scales"

from sklearn.pipeline import make_pipeline
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import StandardScaler

# 3. Impute missing values, encode categories, and standardize
preprocessor = make_pipeline(
    SimpleImputer(strategy="median"),
    StandardScaler()
)

# 4. Transform the feature matrix
X_processed = preprocessor.fit_transform(X)

# Retrieve the names of the transformed features
feature_names = preprocessor.get_feature_names_out()
print("Feature names:", feature_names)

"This cell gives size metrics for reference"

print("Number of reviews:", X_processed.shape[0])
print("Number of features:", X_processed.shape[1])
print(
    "Approximate matrix size in memory:",
    round(X_processed.nbytes / (1024**2), 2),
    "MB"
)

"This cells fits and runs the PCA"

# 5. Fit PCA
pca = PCA()
X_pca = pca.fit_transform(X_processed)

pca_df = pd.DataFrame(
    X_pca,
    columns=[f"PC{i+1}" for i in range(X_pca.shape[1])],
    index=review_df.index
)

pca_df["score"] = y

# 6. Explained variance
explained_variance = pca.explained_variance_ratio_
cumulative_variance = np.cumsum(explained_variance)

variance_df = pd.DataFrame({
    "Principal Component": pca_df.columns[:-1],
    "Explained Variance Ratio": explained_variance,
    "Cumulative Explained Variance": cumulative_variance
})

print("\nExplained variance:")
print(variance_df.round(4))

"This cell plots the explained varance above"

# 7. Plot explained variance
plt.figure(figsize=(9, 5))

plt.bar(
    range(1, len(explained_variance) + 1),
    explained_variance,
    alpha=0.7,
    label="Individual variance"
)

plt.plot(
    range(1, len(cumulative_variance) + 1),
    cumulative_variance,
    marker="o",
    color="red",
    label="Cumulative variance"
)

plt.xlabel("Principal Component")
plt.ylabel("Explained Variance Ratio")
plt.title("PCA of Musical Features")
plt.xticks(range(1, len(explained_variance) + 1))
plt.legend()
plt.tight_layout()
plt.show()

# 8. Inspect feature loadings
loadings = pd.DataFrame(
    pca.components_.T,
    index=features,
    columns=[f"PC{i+1}" for i in range(len(features))]
)

print("\nFeature loadings for PC1 and PC2:")
print(loadings[["PC1", "PC2"]].round(3))

"This cell visualizes albums by reviw score using its first two PCs"

plt.figure(figsize=(10, 7))

scatter = plt.scatter(
    pca_df["PC1"],
    pca_df["PC2"],
    c=pca_df["score"],
    cmap="viridis",
    alpha=0.7,
    s=35,
    edgecolors="none"
)

plt.colorbar(scatter, label="Pitchfork Review Score")

plt.xlabel(
    f"PC1 ({explained_variance[0]:.1%} variance)"
)
plt.ylabel(
    f"PC2 ({explained_variance[1]:.1%} variance)"
)

plt.title("PCA of Musical Features Colored by Review Score")
plt.tight_layout()
plt.show()

"This cells reiterates the features"

"""
Large absolute loadings indicate features that contribute strongly to a component.
Features with loadings of the same sign tend to contribute in the same direction along that component.
Features with opposite signs contribute in opposing directions.
A component might capture a contrast between energetic, loud music and quieter, more acoustic music, for example, depending on your actual results.
Remember that the sign of a component is arbitrary, so interpret the relative signs and magnitudes rather than whether a loading is positive or negative in isolation.
"""

# Create loadings DataFrame with original feature names
loadings = pd.DataFrame(
    pca.components_.T,
    index=features,
    columns=[f"PC{i+1}" for i in range(len(features))]
)

# Print the strongest contributors to PC1 and PC2
for pc in ["PC1", "PC2"]:
    print(f"\nLargest absolute loadings for {pc}:")

    print(
        loadings[pc]
        .sort_values(key=abs, ascending=False)
        .head(11)
        .round(3)
    )

# Plot feature loadings for the first two components
plt.figure(figsize=(9, 7))

sns.heatmap(
    loadings[["PC1", "PC2"]],
    annot=True,
    cmap="coolwarm",
    center=0,
    fmt=".2f"
)

plt.title("Musical Feature Loadings: PC1 and PC2")
plt.tight_layout()
plt.show()

"This cells examins features against review score"

"""
PCA is unsupervised, so it doesn't directly identify which features predict score.
This step calculates Pearson correlations between the original numerical features and the review score.
"""

# Combine original numerical features with review score
numeric_df = df.loc[
    df["score"].notna(),
    features + ["score"]
].copy()

# Calculate correlations with score
score_correlations = (
    numeric_df.corr(numeric_only=True)["score"]
    .drop("score")
    .sort_values()
)

# Plot correlations
plt.figure(figsize=(9, 6))

colors = [
    "steelblue" if value < 0 else "darkorange"
    for value in score_correlations
]

score_correlations.plot(
    kind="barh",
    color=colors
)

plt.axvline(0, color="black", linewidth=0.8)
plt.xlabel("Pearson Correlation with Review Score")
plt.title("Musical Feature Correlations with Pitchfork Scores")
plt.tight_layout()
plt.show()

print("\nFeature correlations with review score:")
print(score_correlations.round(3))